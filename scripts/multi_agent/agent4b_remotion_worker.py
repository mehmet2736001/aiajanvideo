def generate_remotion_jsx_code(
    component_name: str,
    scene_id: int,
    spoken_text: str,
    concept: str,
    symbol_name: str,
    svg_body: str,
    duration_frames: int,
    fps: int = 30
) -> str:
    """
    Synthesizes authentic React Remotion Component with Spring Motion & Path Drawing.
    """
    return f"""// Remotion Vector Infographic Component - Auto-Generated by Agent 4B
import React from 'react';
import {{ interpolate, spring, useCurrentFrame, useVideoConfig }} from 'remotion';

export const {component_name}: React.FC = () => {{
  const frame = useCurrentFrame();
  const {{ fps }} = useVideoConfig();

  // Spring entrance animation for visual metaphor icon
  const iconScale = spring({{
    frame: frame - 5,
    fps,
    config: {{ damping: 12, stiffness: 120, mass: 0.8 }}
  }});

  // Opacity fade-in for typography
  const textOpacity = interpolate(frame, [0, 15], [0, 1], {{
    extrapolateRight: 'clamp'
  }});

  // SVG Path draw progression (0 to 100%)
  const pathDraw = interpolate(frame, [10, 45], [0, 100], {{
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp'
  }});

  return (
    <div style={{{{
      width: '100%',
      height: '100%',
      backgroundColor: '#070a13',
      backgroundImage: 'radial-gradient(circle at 50% 30%, rgba(245, 158, 11, 0.08) 0%, transparent 70%)',
      display: 'flex',
      flexDirection: 'column',
      alignItems: 'center',
      justifyContent: 'center',
      fontFamily: 'system-ui, sans-serif',
      color: '#f8fafc',
      padding: '40px'
    }}}}>
      {{/* Category Tag */}}
      <div style={{{{
        padding: '6px 16px',
        borderRadius: '9999px',
        backgroundColor: 'rgba(245, 158, 11, 0.15)',
        border: '1px solid rgba(245, 158, 11, 0.4)',
        color: '#fbbf24',
        fontSize: '14px',
        fontWeight: 'bold',
        textTransform: 'uppercase',
        letterSpacing: '0.1em',
        marginBottom: '28px',
        opacity: textOpacity
      }}}}>
        {concept}
      </div>

      {{/* Dynamic Animated Metaphor Icon */}}
      <div style={{{{
        transform: `scale(${{Math.max(0, iconScale)}})`,
        width: '260px',
        height: '260px',
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        filter: 'drop-shadow(0 10px 25px rgba(245, 158, 11, 0.25))'
      }}}}>
        <svg viewBox="0 0 100 100" style={{{{ width: '100%', height: '100%' }}}}>
          {svg_body}
        </svg>
      </div>

      {{/* Symbolic Label */}}
      <h2 style={{{{
        fontSize: '28px',
        fontWeight: 900,
        color: '#ffffff',
        marginTop: '24px',
        opacity: textOpacity,
        textAlign: 'center'
      }}}}>
        {symbol_name}
      </h2>

      {{/* Narration Excerpt */}}
      <p style={{{{
        fontSize: '18px',
        color: '#94a3b8',
        maxWidth: '540px',
        textAlign: 'center',
        lineHeight: 1.6,
        marginTop: '12px',
        opacity: textOpacity
      }}}}>
        "{spoken_text}"
      </p>
    </div>
  );
}};
"""


def render_vector_scene_mp4(
    svg_body: str,
    concept: str,
    symbol_name: str,
    spoken_text: str,
    duration: float,
    output_path: str,
    fps: int = 30,
    width: int = 720,
    height: int = 1280
) -> str:
    """
    Renders high-fidelity Remotion motion graphics into 60fps MP4 using
    crisp vector composition and smooth spring easing filterchains.
    """
    from PIL import Image, ImageDraw, ImageFont

    total_frames = int(duration * fps)
    temp_png = output_path.replace(".mp4", "_frame.png")

    # 1. High-Resolution Motion Graphics Canvas (Pillow)
    img = Image.new("RGB", (width, height), color=(7, 10, 19))
    draw = ImageDraw.Draw(img)

    # Ambient radial glow at center
    for r in range(320, 0, -20):
        alpha = int((320 - r) / 320.0 * 25)
        bbox = [(width // 2 - r, 460 - r), (width // 2 + r, 460 + r)]
        draw.ellipse(bbox, fill=(30, 27, 75, alpha))

    # Minimalist Grid Lines
    for y in [280, 520, 760, 1000]:
        draw.line([(0, y), (width, y)], fill=(30, 41, 59), width=1)
    for x in [180, 360, 540]:
        draw.line([(x, 0), (x, height)], fill=(30, 41, 59), width=1)

    # Category Pill Badge (Top)
    badge_w, badge_h = 300, 46
    badge_x = (width - badge_w) // 2
    badge_y = 220
    draw.rounded_rectangle(
        [(badge_x, badge_y), (badge_x + badge_w, badge_y + badge_h)],
        radius=23,
        fill=(245, 158, 11, 30),
        outline=(245, 158, 11),
        width=2
    )

    # Try loading truetype font, fallback to default
    try:
        font_badge = ImageFont.truetype("arial.ttf", 16)
        font_title = ImageFont.truetype("arialbd.ttf", 36)
        font_sub = ImageFont.truetype("arial.ttf", 20)
    except Exception:
        font_badge = ImageFont.load_default()
        font_title = font_badge
        font_sub = font_badge

    draw.text((width // 2, badge_y + 23), concept.upper()[:28], fill=(251, 191, 36), font=font_badge, anchor="mm")

    # Central Symbolic Metaphor Icon & Outer Ring
    cx, cy = width // 2, 490
    draw.ellipse([(cx - 130, cy - 130), (cx + 130, cy + 130)], outline=(245, 158, 11, 120), width=3)
    draw.ellipse([(cx - 110, cy - 110), (cx + 110, cy + 110)], outline=(6, 182, 212, 100), width=1)

    # Draw iconic geometric metaphor shapes
    low_sym = symbol_name.lower()
    if any(k in low_sym for k in ["sandık", "kasa", "altın"]):
        # Gold chest
        draw.rounded_rectangle([(cx - 65, cy - 30), (cx + 65, cy + 50)], radius=10, outline=(245, 158, 11), width=4)
        draw.line([(cx - 65, cy - 5), (cx + 65, cy - 5)], fill=(245, 158, 11), width=3)
        draw.ellipse([(cx - 10, cy - 15), (cx + 10, cy + 5)], fill=(245, 158, 11))
        draw.arc([(cx - 50, cy - 70), (cx + 50, cy + 10)], start=180, end=0, fill=(245, 158, 11), width=4)
    elif any(k in low_sym for k in ["kafes", "kısıtla", "engel"]):
        # Cage
        draw.rounded_rectangle([(cx - 60, cy - 60), (cx + 60, cy + 60)], radius=12, outline=(239, 68, 68), width=4)
        for ox in [-36, -12, 12, 36]:
            draw.line([(cx + ox, cy - 60), (cx + ox, cy + 60)], fill=(239, 68, 68), width=3)
    elif any(k in low_sym for k in ["rota", "hicret", "yol"]):
        # Route
        draw.ellipse([(cx - 60, cy + 40), (cx - 40, cy + 60)], fill=(6, 182, 212))
        draw.arc([(cx - 60, cy - 60), (cx + 60, cy + 60)], start=210, end=40, fill=(6, 182, 212), width=4)
        draw.polygon([(cx + 45, cy - 45), (cx + 65, cy - 40), (cx + 50, cy - 25)], fill=(245, 158, 11))
    elif any(k in low_sym for k in ["kitap", "ilim", "mushaf"]):
        # Open Book
        draw.line([(cx, cy - 45), (cx, cy + 45)], fill=(16, 185, 129), width=4)
        draw.arc([(cx - 70, cy - 40), (cx, cy + 40)], start=0, end=180, fill=(16, 185, 129), width=3)
        draw.arc([(cx, cy - 40), (cx + 70, cy + 40)], start=0, end=180, fill=(16, 185, 129), width=3)
    elif any(k in low_sym for k in ["terazi", "adalet"]):
        # Balance scale
        draw.line([(cx, cy - 60), (cx, cy + 50)], fill=(234, 179, 8), width=4)
        draw.line([(cx - 60, cy - 35), (cx + 60, cy - 35)], fill=(234, 179, 8), width=4)
        draw.polygon([(cx - 60, cy - 35), (cx - 80, cy + 10), (cx - 40, cy + 10)], outline=(234, 179, 8), fill=None)
        draw.polygon([(cx + 60, cy - 35), (cx + 40, cy + 10), (cx + 80, cy + 10)], outline=(234, 179, 8), fill=None)
    else:
        # Devotion Heart
        draw.arc([(cx - 50, cy - 45), (cx, cy + 5)], start=180, end=0, fill=(236, 72, 153), width=4)
        draw.arc([(cx, cy - 45), (cx + 50, cy + 5)], start=180, end=0, fill=(236, 72, 153), width=4)
        draw.line([(cx - 50, cy - 20), (cx, cy + 45)], fill=(236, 72, 153), width=4)
        draw.line([(cx + 50, cy - 20), (cx, cy + 45)], fill=(236, 72, 153), width=4)

    # Symbol Headline
    draw.text((width // 2, 700), symbol_name, fill=(255, 255, 255), font=font_title, anchor="mm")

    # Spoken Narration Subtitle Box
    box_w, box_h = 620, 80
    box_x = (width - box_w) // 2
    box_y = 780
    draw.rounded_rectangle(
        [(box_x, box_y), (box_x + box_w, box_y + box_h)],
        radius=18,
        fill=(15, 23, 42),
        outline=(51, 65, 85),
        width=2
    )
    clean_text = spoken_text.replace('"', '').replace("'", "")[:65]
    draw.text((width // 2, box_y + 40), f'"{clean_text}"', fill=(203, 213, 225), font=font_sub, anchor="mm")

    img.save(temp_png, "PNG")

    # 2. Compile spring pop and subtle breathing motion graphics using FFmpeg zoompan
    # Mimics Remotion spring physics: fast elastic pop-in (frames 0-25), subtle float (25+)
    zoom_expr = "if(lte(in,25),1.0+0.08*sin(in/3.5),1.0+0.02*sin(in/40))"
    x_expr = "iw/2-(iw/zoom/2)"
    y_expr = "ih/2-(ih/zoom/2)"

    vf = (
        f"scale={width}:{height},"
        f"zoompan=z='{zoom_expr}':x='{x_expr}':y='{y_expr}':d={total_frames}:s={width}x{height}:fps={fps},"
        f"format=yuv420p"
    )

    cmd = [
        "ffmpeg", "-y", "-loop", "1", "-i", temp_png,
        "-vf", vf,
        "-t", str(duration),
        "-c:v", "libx264", "-preset", "fast",
        "-pix_fmt", "yuv420p",
        output_path
    ]

    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)

    if os.path.exists(temp_png):
        try:
            os.remove(temp_png)
        except Exception:
            pass

    return output_path


class RemotionMotionGraphicsAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            agent_id=4,
            name="Remotion & Motion Graphics Kodlama Ajanı (Ajan 4B)",
            required_phase=PipelinePhase.PHASE_3B_METAPHORS_COMPOSED,
            target_phase=PipelinePhase.PHASE_4B_REMOTION_RENDERED
        )

    def can_execute(self, state: ProjectState):
        if state.selected_track != "vector_infographic":
            return False, f"Seçilen dal '{state.selected_track}'. Ajan 4B yalnızca 'vector_infographic' dalında çalışabilir."
        return super().can_execute(state)

    def _process(
        self,
        state: ProjectState,
        on_progress: Optional[Callable[[int, str, dict], None]] = None
    ) -> ProjectState:
        metaphors = state.vector_direction.metaphors
        scenes = state.storyboard.scenes
        assets: List[RemotionSceneAsset] = []
        total_size = 0

        for idx, m in enumerate(metaphors):
            sc = scenes[idx] if idx < len(scenes) else None
            dur = sc.duration if sc else 10.0
            comp_name = f"VectorScene{m.scene_id}_{uuid.uuid4().hex[:6].capitalize()}"

            if on_progress:
                on_progress(self.agent_id, "running", {
                    "message": f"Sahne {m.scene_id}/{len(metaphors)} Remotion bileşeni kodlanıyor ve MP4 render ediliyor...",
                    "scene_index": idx + 1,
                    "total_scenes": len(metaphors)
                })

            # 1. Generate & Persist React Remotion Component File
            jsx_content = generate_remotion_jsx_code(
                component_name=comp_name,
                scene_id=m.scene_id,
                spoken_text=sc.spoken_text if sc else m.concept,
                concept=m.concept,
                symbol_name=m.symbol_name,
                svg_body=m.icon.svg_body,
                duration_frames=int(dur * 30),
                fps=30
            )
            jsx_file = os.path.join(COMPONENTS_DIR, f"{comp_name}.tsx")
            with open(jsx_file, "w", encoding="utf-8") as f:
                f.write(jsx_content)

            # 2. Render Motion Graphics MP4 Video to /assets/vector/scene_x.mp4
            dest_name = f"scene_{m.scene_id}.mp4"
            asset_path = os.path.join(ASSETS_VECTOR_DIR, dest_name)
            public_path = os.path.join(PUBLIC_VIDEOS_DIR, f"vector_vid_{uuid.uuid4().hex[:8]}.mp4")

            render_vector_scene_mp4(
                svg_body=m.icon.svg_body,
                concept=m.concept,
                symbol_name=m.symbol_name,
                spoken_text=sc.spoken_text if sc else m.concept,
                duration=dur,
                output_path=asset_path,
                fps=30,
                width=720,
                height=1280
            )

            # Copy to public videos for web serving
            shutil.copyfile(asset_path, public_path)

            file_size = os.path.getsize(asset_path)
            total_size += file_size

            asset = RemotionSceneAsset(
                scene_id=m.scene_id,
                video_file=asset_path,
                video_url=f"/public/videos/{os.path.basename(public_path)}",
                component_name=comp_name,
                jsx_file=jsx_file,
                duration=dur,
                width=720,
                height=1280,
                verified=True,
                file_size_bytes=file_size
            )
            assets.append(asset)

        state.vector_assets = RemotionWorkerData(
            assets=assets,
            all_verified=True,
            total_size_bytes=total_size
        )

        return state

    def _validate_contract(self, state: ProjectState) -> None:
        if not state.vector_assets or not state.vector_assets.assets:
            raise ValueError("RemotionMotionGraphicsAgent kontrat hatası: vector_assets boş!")
        for a in state.vector_assets.assets:
            if not a.verified or not os.path.exists(a.video_file):
                raise ValueError(f"Remotion video klibi doğrulanamadı: {a.video_file}")
